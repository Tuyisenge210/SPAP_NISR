import { createFileRoute } from "@tanstack/react-router";
import { useEffect, useMemo, useState } from "react";
import { Download, FileSpreadsheet, RefreshCw } from "lucide-react";
import { AppShell } from "@/components/lfs/app-shell";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { getStandardTables, type TablesPayload } from "@/lib/api/lfs";
import { SPAP_ENV_BADGE } from "@/lib/env";

export const Route = createFileRoute("/tables")({
  head: () => ({
    meta: [
      { title: "Tables — SPAP" },
      { name: "description", content: "Production chapter tables from the backend analytical engine." },
      { property: "og:title", content: "Statistical tables — SPAP" },
      { property: "og:description", content: "Production LFS tables generated by the Python chapter engine." },
    ],
  }),
  component: TablesPage,
});

function toCsv(table: { name: string; headers: string[]; rows: (string | number)[][] }) {
  const escape = (value: string | number) => `"${String(value).replaceAll('"', '""')}"`;
  const csv = [table.headers, ...table.rows].map((row) => row.map(escape).join(",")).join("\r\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${table.name.replace(/[^a-z0-9]+/gi, "_").toLowerCase()}.csv`;
  link.click();
  URL.revokeObjectURL(url);
}

function rowsToTable(name: string, rows: Array<Record<string, unknown>>) {
  if (!rows.length) return { name, headers: ["Message"], rows: [["No rows returned for this table."]] };
  const headers = Object.keys(rows[0] ?? {});
  return {
    name,
    headers,
    rows: rows.map((row) => headers.map((header) => {
      const value = row[header];
      if (value == null) return "";
      if (typeof value === "number" && Number.isFinite(value)) return value;
      return String(value);
    })),
  };
}

function TablesPage() {
  const [year, setYear] = useState<number | undefined>(undefined);
  const [payload, setPayload] = useState<TablesPayload | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [reloadKey, setReloadKey] = useState(0);

  useEffect(() => {
    const controller = new AbortController();
    setLoading(true);
    setError(null);
    getStandardTables(year, controller.signal)
      .then(setPayload)
      .catch((reason: unknown) => {
        if (reason instanceof Error && reason.name === "AbortError") return;
        setError(reason instanceof Error ? reason.message : "Unable to load production tables from /api/v1/standard.");
      })
      .finally(() => {
        if (!controller.signal.aborted) setLoading(false);
      });
    return () => controller.abort();
  }, [year, reloadKey]);

  const tables = useMemo(() => {
    const entries = Object.entries(payload?.tables ?? {});
    return entries.map(([name, rows]) => rowsToTable(name, rows as Array<Record<string, unknown>>));
  }, [payload]);

  const years = payload?.years ?? [];

  return (
    <AppShell>
      <div className="mb-4 flex flex-wrap items-end justify-between gap-3">
        <div>
          <div className="mb-2 inline-flex rounded border border-emerald-500 bg-emerald-50 px-2 py-1 text-[10px] font-bold tracking-wider text-emerald-800">[{SPAP_ENV_BADGE}]</div>
          <h1 className="text-2xl font-semibold tracking-tight">Production LFS tables</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Source: backend <code>/api/v1/standard</code> and Python chapter engine (<code>labour_analytics/table_engine.py</code>).
          </p>
        </div>
        <div className="flex items-center gap-2">
          <select
            className="h-9 rounded border border-slate-300 bg-white px-2 text-sm"
            value={year ?? ""}
            onChange={(e) => setYear(e.target.value ? Number(e.target.value) : undefined)}
            aria-label="Select year"
          >
            <option value="">All available years</option>
            {years.map((y) => <option key={y} value={y}>{y}</option>)}
          </select>
          <Button variant="outline" onClick={() => setReloadKey((k) => k + 1)} disabled={loading}>
            <RefreshCw className="mr-2 h-4 w-4" />Reload
          </Button>
        </div>
      </div>

      {error && (
        <Alert variant="destructive" className="mb-4">
          <AlertDescription>{error}</AlertDescription>
        </Alert>
      )}

      {loading && !payload ? (
        <div className="rounded border bg-white p-6 text-sm text-muted-foreground">Loading production tables from backend API…</div>
      ) : (
        <div className="space-y-4">
          <div className="text-xs text-muted-foreground">
            Year filter: {payload?.year ?? "all"} · years: {years.join(", ") || "unknown"} · source records: {payload?.source_records ?? "n/a"} · weight: {payload?.weight_column ?? "n/a"}
          </div>
          {tables.map((t) => (
            <Card key={t.name}>
              <CardHeader className="flex flex-row items-center justify-between space-y-0 pb-2">
                <CardTitle className="text-sm font-semibold">{t.name}</CardTitle>
                <Button size="sm" variant="outline" onClick={() => toCsv(t)}>
                  <Download className="mr-1.5 h-3.5 w-3.5" />CSV
                </Button>
              </CardHeader>
              <CardContent className="overflow-x-auto">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="border-b text-left text-xs uppercase tracking-wider text-muted-foreground">
                      {t.headers.map((h) => <th key={h} className="py-2 pr-4 font-medium">{h}</th>)}
                    </tr>
                  </thead>
                  <tbody>
                    {t.rows.map((r, i) => (
                      <tr key={i} className="border-b last:border-0">
                        {r.map((c, j) => (
                          <td key={j} className={"py-2 pr-4 tabular-nums " + (j === 0 ? "font-medium" : "")}>{String(c)}</td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </CardContent>
            </Card>
          ))}
          {!tables.length && !loading && (
            <Alert>
              <AlertDescription>No production tables were returned. Ensure the backend API is running and harmonized outputs are available.</AlertDescription>
            </Alert>
          )}
        </div>
      )}
    </AppShell>
  );
}
